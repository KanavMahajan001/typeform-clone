"use client";

import { useEffect, type ReactNode } from "react";
import { CloseIcon } from "./Icons";

interface Props {
  open: boolean;
  onClose: () => void;
  title?: string;
  children: ReactNode;
  width?: string;
}

export function Modal({ open, onClose, title, children, width = "max-w-md" }: Props) {
  useEffect(() => {
    if (!open) return;
    const onKey = (event: KeyboardEvent) => event.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, onClose]);

  if (!open) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 p-4" onMouseDown={onClose}>
      <div
        role="dialog"
        aria-modal="true"
        className={`relative w-full ${width} rounded-2xl bg-admin-surface p-8 text-admin-text shadow-[0_8px_30px_rgba(0,0,0,0.2)]`}
        onMouseDown={(event) => event.stopPropagation()}
      >
        <button
          type="button"
          onClick={onClose}
          aria-label="Close"
          className="absolute right-4 top-4 rounded-md p-1 text-admin-muted hover:bg-admin-hover"
        >
          <CloseIcon width={18} height={18} />
        </button>
        {title && <h2 className="mb-6 pr-8 text-2xl font-medium">{title}</h2>}
        {children}
      </div>
    </div>
  );
}
